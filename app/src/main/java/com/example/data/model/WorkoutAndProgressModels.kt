package com.example.data.model

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey

enum class WorkoutSplitType(val title: String, val subtitle: String) {
    AB("Divisão AB (Upper / Lower)", "2 treinos alternados • Ideal para 3-4 dias/semana"),
    ABC("Divisão ABC (Push / Pull / Legs)", "3 treinos completos • Frequência alta 2x/semana"),
    ABCDE("Divisão ABCDE (Hipertrofia Avançada)", "5 treinos isolados • Foco intenso em cada grupamento"),
    CUSTOM("Treinos Personalizados", "Crie sua própria rotina customizada do zero")
}

@Entity(tableName = "shopping_items")
data class ShoppingItem(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val name: String,
    val category: FoodCategory,
    val quantity: Float, // My quantity
    val partnerQuantity: Float = 0f, // Partner / Brother quantity
    val partnerName: String = "",
    val isJointItem: Boolean = false,
    val unit: String, // "kg", "g", "un", "potes (1kg)", "cartelas (30un)"
    val periodDays: Int = 30, // Default to 30 days monthly shopping list
    val isChecked: Boolean = false,
    val estimatedPrice: Float = 0f, // Total combined price
    val myEstimatedPrice: Float = 0f,
    val partnerEstimatedPrice: Float = 0f,
    val isAutoGenerated: Boolean = true,
    val notes: String = ""
) {
    val totalCombinedQuantity: Float
        get() = if (isJointItem) quantity + partnerQuantity else quantity
}

@Entity(tableName = "workout_routines")
data class WorkoutRoutine(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val splitType: WorkoutSplitType = WorkoutSplitType.ABCDE,
    val letter: String, // "A", "B", "C", "D", "E"
    val title: String, // "Peito, Deltoide Anterior e Tríceps"
    val dayOfWeekLabel: String = "Segunda-feira",
    val targetMuscleGroups: String = "Peitoral, Ombros, Tríceps",
    val estimatedDurationMinutes: Int = 60,
    val orderIndex: Int = 0
)

@Entity(
    tableName = "workout_exercises",
    indices = [Index(value = ["routineId"])]
)
data class WorkoutExercise(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val routineId: Long,
    val exerciseName: String,
    val muscleGroup: String,
    val sets: Int = 4,
    val repsMin: Int = 8,
    val repsMax: Int = 12,
    val currentWeightKg: Float = 30f,
    val restSeconds: Int = 90,
    val orderIndex: Int = 0,
    val notes: String = "Cadência 2-0-2, até a falha na última série",
    val biomechanicsGuide: String = "Mantenha a coluna neutra, escápulas aduzidas e respire na fase excêntrica.",
    val gifDemonstrationUrl: String = "https://fitnessprogramer.com/exercise/",
    val isCompletedInCurrentSession: Boolean = false
)

@Entity(
    tableName = "workout_logs",
    indices = [
        Index(value = ["routineId"]),
        Index(value = ["dateMillis"])
    ]
)
data class WorkoutLog(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val routineId: Long,
    val routineName: String,
    val dateMillis: Long,
    val durationMinutes: Int,
    val totalVolumeKg: Float, // Sum of (sets * reps * weight)
    val totalSetsCompleted: Int,
    val perceivedExertion: Int = 8, // RPE 1 to 10
    val notes: String = ""
)

@Entity(
    tableName = "progress_logs",
    indices = [Index(value = ["dateMillis"])]
)
data class ProgressLog(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val dateMillis: Long,
    val dateDisplay: String,
    val weightKg: Float,
    val bodyFatPercentage: Float = 0f,
    val chestCm: Float = 0f,
    val waistCm: Float = 0f,
    val armLeftCm: Float = 0f,
    val armRightCm: Float = 0f,
    val thighCm: Float = 0f,
    val calfCm: Float = 0f,
    val notes: String = "",
    val photoUri: String = ""
)
